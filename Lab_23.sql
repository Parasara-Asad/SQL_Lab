--1. INSERT Procedures: Create stored procedures to insert records into STUDENT tables (SP_INSERT_STUDENT) 

CREATE PROC PR_INSERT_STUDENT
@STDID INT,@SNAME VARCHAR(20),@CITY VARCHAR(20),@SPI DECIMAL(4,2),@BRANCH VARCHAR(20)
AS 
BEGIN
   INSERT INTO STUDENT VALUES (@STDID ,@SNAME,@CITY ,@SPI ,@BRANCH)
END

EXEC PR_INSERT_STUDENT 115,'PUSHTI','RAJKOT',9.48,'COMPUTER'
EXEC PR_INSERT_STUDENT 116,'NIKUNJ','SURAT',8.80,'CHEMICAL' 

SELECT *FROM STUDENT

