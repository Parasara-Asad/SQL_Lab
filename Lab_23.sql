--  UPDATE Procedures: Create stored procedure SP_UPDATE_STUDENT to update Branch in STUDENT table. (Update using studentID) 



CREATE PROC PR_UPDATE_STUDENT 
    @STDID  INT,
    @BRANCH VARCHAR(50)
AS
BEGIN
    UPDATE STUDENT
    SET BRANCH=@BRANCH
    WHERE STDID=@STDID
END;


EXEC PR_UPDATE_STUDENT 115, 'ELECTRICAL';
EXEC PR_UPDATE_STUDENT 116, 'MECHANICAL';


SELECT *FROM STUDENT

--4. DELETE Procedures: Create stored procedure SP_DELETE_STUDENT to delete records from STUDENT where Student Name is RAVI. 

CREATE PROC PR_DELETE_STUDENT
@SNAME VARCHAR(50)
AS
DELETE FROM STUDENT
WHERE SNAME=@SNAME

EXEC PR_DELETE_STUDENT 'RAVI'

--5. SELECT BY PRIMARY KEY: Create stored procedures to select records by primary key 
--(PR_SELECT_STUDENT_BY_ID) from Student table. (Display All Columns) 

CREATE PROCEDURE PR_SELECT_STUDENT_BY_ID
    @STDID INT 
AS
BEGIN
    SELECT *
    FROM STUDENT
    WHERE STDID = @STDID
END;


EXEC PR_SELECT_STUDENT_BY_ID 115;
    

--6. Create a stored procedure that shows details of the first 5 students ordered by SPI (Highest First). 

CREATE PROCEDURE PR_TOP_5_STUDENTS
AS
BEGIN
    SELECT TOP 5 *
    FROM STUDENT
    ORDER BY SPI DESC;
END;

EXEC PR_TOP_5_STUDENTS

